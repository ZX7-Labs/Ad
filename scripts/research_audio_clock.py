"""Measure unchanged BODY audio timing against sample-unit FFmpeg operations.

Research only: no registered runtime behavior is modified. All media is generated
in a temporary directory. A successful measurement can report BODY mismatches;
use --require-conformance to make those mismatches a failing acceptance gate.
The diagnostic renders the compiled audio branch to PCM and sinks video. It is
not a normal MP4 delivery, semantic listening test or autonomous creative trial.
"""
from __future__ import annotations

import argparse
import array
from collections import Counter
from fractions import Fraction
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import wave

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from studio_next.composite_mix import actual_composite_command
from studio_next.media_vault import MediaVault

BUS_RATE = 48000
OUTPUT_SAMPLES = 4800
CLIP_BUS_SAMPLES = 3840
OFFSETS = (0, 1, 23, 24, 25, 47, 48, 49, 2399)
TRIMS = (0, 1, 47)


def run(command):
    return subprocess.run(command, check=True, capture_output=True, timeout=45).stdout


def version(binary):
    return run([binary, "-version"]).decode().splitlines()[0]


def pcm_peaks(path):
    with wave.open(str(path), "rb") as stream:
        channels = stream.getnchannels()
        rate = stream.getframerate()
        count = stream.getnframes()
        if stream.getsampwidth() != 2 or channels != 2 or rate != BUS_RATE:
            raise ValueError("Diagnostic must decode 48 kHz stereo signed-16 PCM")
        samples = array.array("h", stream.readframes(count))
    if sys.byteorder != "little":
        samples.byteswap()
    if count != OUTPUT_SAMPLES or len(samples) != count * channels:
        raise ValueError("Diagnostic output does not contain the exact requested samples")
    peaks = []
    for channel in range(channels):
        signal = samples[channel::channels]
        if max(map(abs, signal), default=0) < 1000:
            raise ValueError("Diagnostic impulse disappeared")
        peaks.append(max(range(count), key=lambda i: abs(signal[i])))
    return {"channels": channels, "samples": count, "peak_samples": peaks}


def fixture(root, rate, channels, trim):
    path = root / f"impulse-{rate}-{channels}-{trim}.wav"
    count = rate // 5
    values = array.array("h", [0]) * (count * channels)
    # Separate stereo peak locations catch swapped/lost channels. Mono is
    # deliberately upmixed by BOTH routes, matching the existing bus contract.
    for channel in range(channels):
        at = trim + 257 + channel * 113
        values[at * channels + channel] = 24000 - channel * 6000
    if sys.byteorder != "little":
        values.byteswap()
    with wave.open(str(path), "wb") as stream:
        stream.setnchannels(channels)
        stream.setsampwidth(2)
        stream.setframerate(rate)
        stream.writeframes(values.tobytes())
    return path


def reference(source, rate, trim, offset, output):
    # Source sample indices are independent of BODY's float-second trim path.
    # Duration is exactly 80 ms for both input rates used here.
    end = trim + rate * CLIP_BUS_SAMPLES // BUS_RATE
    graph = (f"[0:a:0]atrim=start_sample={trim}:end_sample={end},"
             "asetpts=PTS-STARTPTS,aresample=48000,"
             "aformat=channel_layouts=stereo,"
             f"adelay=delays={offset}S:all=1,apad,"
             f"atrim=end_sample={OUTPUT_SAMPLES}[aout]")
    run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-nostdin", "-y",
         "-i", str(source), "-filter_complex", graph, "-map", "[aout]",
         "-c:a", "pcm_s16le", str(output)])
    return pcm_peaks(output)


def measure(root):
    vault = MediaVault(root / "vault")
    rows = []
    for rate in (44100, 48000):
        for channels in (1, 2):
            for trim in TRIMS:
                source = fixture(root, rate, channels, trim)
                proof = vault.ingest(source, mime="audio/wav", rights="owner_supplied",
                                     source_type="owner_upload", source_id=source.stem,
                                     evidence="Synthetic research PCM generated by this script",
                                     owner_or_generator="synthetic-test-generator")
                base = reference(source, rate, trim, 0, root / "reference.wav")
                for offset in OFFSETS:
                    plan = {"canvas": {"width": 32, "height": 32, "fps": 24,
                                       "duration": OUTPUT_SAMPLES / BUS_RATE,
                                       "background": "#000000"},
                            "video_layers": [], "audio_tracks": [{
                                "id": "synthetic-impulse", "source": source.name,
                                "asset_id": proof["asset_id"],
                                "attestation_id": proof["attestation_id"],
                                "start": offset / BUS_RATE, "source_in": trim / rate,
                                "duration": CLIP_BUS_SAMPLES / BUS_RATE, "gain_db": 0}]}
                    cmd = actual_composite_command(plan, root, vault, root / "unused.mp4")
                    index = cmd.index("-filter_complex")
                    graph = cmd[index + 1] + ";[vout]nullsink"
                    # Keep every input and the compiled graph, but replace the
                    # output transport. No filter/timing behavior is repaired.
                    output = root / "body.wav"
                    ref = reference(source, rate, trim, offset, root / "reference.wav")
                    expected = [sample + offset for sample in base["peak_samples"]]
                    if ref["peak_samples"] != expected:
                        raise ValueError("Independent sample-unit reference disagrees with shift oracle")
                    body = None
                    failure = None
                    try:
                        run(cmd[:index] + ["-filter_complex", graph, "-map", "[aout]",
                                          "-c:a", "pcm_s16le", str(output)])
                        body = pcm_peaks(output)
                    except subprocess.CalledProcessError as exc:
                        # An adapter-generated command rejected by the real
                        # engine is a measured conformance failure. Reference
                        # failures and malformed PCM still abort the experiment.
                        failure = {"returncode": exc.returncode,
                                   "stderr": exc.stderr.decode(errors="replace")[:2000]}
                    delta = ([a - b for a, b in zip(body["peak_samples"], expected)]
                             if body else None)
                    rows.append({"source_rate": rate, "source_channels": channels,
                                 "source_trim_samples": trim, "placement_bus_samples": offset,
                                 "placement_seconds_exact": str(Fraction(offset, BUS_RATE)),
                                 "body_peak_samples": body["peak_samples"] if body else None,
                                 "reference_peak_samples": ref["peak_samples"],
                                 "body_execution_error": failure,
                                 "delta_samples": delta, "matches": delta is not None and not any(delta),
                                 "body_graph_sha256": hashlib.sha256(graph.encode()).hexdigest()})
    return rows


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--summary-out", type=Path)
    parser.add_argument("--require-conformance", action="store_true")
    options = parser.parse_args(argv)
    for binary in ("ffmpeg", "ffprobe", "git"):
        if not shutil.which(binary):
            parser.error(f"Required real executable unavailable: {binary}")
    repo = Path(__file__).resolve().parents[1]
    head = run(["git", "-C", str(repo), "rev-parse", "HEAD"]).decode().strip()
    dirty = bool(run(["git", "-C", str(repo), "status", "--porcelain"]))
    with tempfile.TemporaryDirectory(prefix="zx7-research-audio-") as directory:
        rows = measure(Path(directory))
    mismatches = [row for row in rows if not row["matches"]]
    groups = Counter((r["source_rate"], r["source_channels"]) for r in mismatches)
    summary = {"schema": 1, "source_commit": head, "working_tree_dirty": dirty,
               "probe_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
               "composition_adapter_sha256": hashlib.sha256(
                   (repo / "studio_next/composite_mix.py").read_bytes()).hexdigest(),
               "tools": {name: version(name) for name in ("ffmpeg", "ffprobe")},
               "bus_rate": BUS_RATE, "output_samples_per_channel": OUTPUT_SAMPLES,
               "cases": len(rows), "matching_cases": len(rows) - len(mismatches),
               "mismatching_cases": len(mismatches),
               "body_execution_failures": sum(r["body_execution_error"] is not None for r in rows),
               "decoded_timing_mismatches": sum(r["delta_samples"] is not None and not r["matches"]
                                                for r in rows),
               "worst_absolute_delta_samples": max((abs(d) for r in rows
                                                      for d in (r["delta_samples"] or [])), default=None),
               "mismatches_by_source": [{"rate": rate, "channels": channels, "count": count}
                                        for (rate, channels), count in sorted(groups.items())],
               "representative_mismatches": mismatches[:3],
               "representative_execution_error": next(
                   (r for r in rows if r["body_execution_error"] is not None), None),
               "reference_shift_oracle_passed": True,
               "body_timing_conformance_passed": not mismatches,
               "scope": "Synthetic compiled audio branch to lossless PCM; video sunk; both routes use current stereo bus",
               "not_established": ["AAC delivery precision", "full sample waveform equivalence",
                                   "professional audio acceptance", "autonomous creative model"]}
    options.out.parent.mkdir(parents=True, exist_ok=True)
    options.out.write_text(json.dumps({"summary": summary, "cases": rows}, indent=2) + "\n")
    if options.summary_out:
        options.summary_out.parent.mkdir(parents=True, exist_ok=True)
        options.summary_out.write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps({k: summary[k] for k in ("source_commit", "working_tree_dirty", "cases",
                     "matching_cases", "mismatching_cases", "body_execution_failures", "worst_absolute_delta_samples",
                     "reference_shift_oracle_passed", "body_timing_conformance_passed")}))
    return 1 if options.require_conformance and mismatches else 0


if __name__ == "__main__":
    raise SystemExit(main())
