"""Matched synthetic editorial probe for existing MLT and FFmpeg BODY routes.

Measures source-frame selection before/after a native revision and reopen.
Opaque full-frame diagnostic plates are deliberately simple: this does not
certify transitions, alpha, sound, color accuracy, craft or model autonomy.
No runtime implementation is changed and no media is kept in the repository.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import time

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from studio_next.body_mlt_editor import export_owned_mlt
from studio_next.body_mlt_render import render_owned_mlt
from studio_next.body_mlt_revision import revise_owned_mlt_project
from studio_next.body_mlt_roundtrip import recover_original_mlt_plan
from studio_next.composite_mix import render_composition
from studio_next.media_vault import MediaVault

WIDTH, HEIGHT, FPS, FRAMES = 64, 48, 12, 12
PITCH = WIDTH * HEIGHT * 3


def run(command, *, data=None):
    return subprocess.run(command, input=data, check=True, capture_output=True, timeout=120).stdout


def decode(path):
    raw = run(["ffmpeg", "-v", "error", "-xerror", "-nostdin", "-i", str(path),
               "-map", "0:v:0", "-pix_fmt", "rgb24", "-f", "rawvideo", "-"])
    if len(raw) != FRAMES * PITCH:
        raise ValueError("Output/source did not decode to the exact diagnostic frame count")
    return [raw[i * PITCH:(i + 1) * PITCH] for i in range(FRAMES)]


def make_sources(root):
    vault = MediaVault(root / "vault")
    records, candidates = [], {}
    for take in range(3):
        # Every take/frame has a distinguishable color; classify decoded bytes
        # against decoded sources, not unencoded RGB assumptions.
        raw = b"".join(bytes((25 + frame * 15, 30 + take * 80, 210 - frame * 10))
                       * (WIDTH * HEIGHT) for frame in range(FRAMES))
        path = root / f"take-{take}.mp4"
        run(["ffmpeg", "-v", "error", "-nostdin", "-y", "-f", "rawvideo",
             "-pix_fmt", "rgb24", "-s", f"{WIDTH}x{HEIGHT}", "-r", str(FPS),
             "-i", "pipe:0", "-frames:v", str(FRAMES), "-c:v", "libx264",
             "-crf", "10", "-pix_fmt", "yuv420p", "-color_primaries", "bt709",
             "-color_trc", "bt709", "-colorspace", "bt709", str(path)], data=raw)
        records.append(vault.ingest(path, mime="video/mp4", rights="owner_supplied",
                                   source_type="owner_upload", source_id=f"synthetic-{take}",
                                   evidence="Synthetic diagnostic plate generated by this probe",
                                   owner_or_generator="synthetic-test-generator"))
        for frame, pixels in enumerate(decode(path)):
            candidates[(take, frame)] = pixels
    return records, candidates


def make_plan(records):
    tracks = []
    for take, first, end, position in ((0, 0, 12, 0), (1, 2, 8, 4), (2, 1, 4, 6)):
        item = records[take]
        tracks.append({"clips": [{"source": "zx7:sha256:" + item["asset_id"],
                                  "asset_id": item["asset_id"],
                                  "attestation_id": item["attestation_id"],
                                  "first_frame": first, "end_frame": end,
                                  "position_frame": position, "audio": "intentional_silence"}]})
    return {"frame_rate": {"numerator": FPS, "denominator": 1},
            "frame_size": {"width": WIDTH, "height": HEIGHT}, "tracks": tracks}


def composition(plan):
    layers = []
    for index, track in enumerate(plan["tracks"]):
        clip = track["clips"][0]
        layers.append({key: clip[key] for key in ("source", "asset_id", "attestation_id")})
        layers[-1].update(id=f"layer-{index}", start=clip["position_frame"] / FPS,
                          source_in=clip["first_frame"] / FPS,
                          duration=(clip["end_frame"] - clip["first_frame"]) / FPS,
                          x=0, y=0, width=WIDTH, height=HEIGHT, opacity=1)
    return {"canvas": {"width": WIDTH, "height": HEIGHT, "fps": FPS,
                       "duration": FRAMES / FPS, "background": "#000000"},
            "video_layers": layers, "audio_tracks": []}


def expected_frames(plan):
    result = []
    for frame in range(FRAMES):
        selected = None
        for take, track in enumerate(plan["tracks"]):
            clip = track["clips"][0]
            local = frame - clip["position_frame"]
            if 0 <= local < clip["end_frame"] - clip["first_frame"]:
                selected = (take, clip["first_frame"] + local)
        if selected is None:
            raise ValueError("Diagnostic oracle has an uncovered picture frame")
        result.append(selected)
    return result


def assess(path, plan, candidates):
    rows = []
    for frame, (pixels, expected) in enumerate(zip(decode(path), expected_frames(plan))):
        errors = {key: sum(abs(a - b) for a, b in zip(pixels, source)) / PITCH
                  for key, source in candidates.items()}
        nearest = min(errors, key=errors.get)
        rows.append({"frame": frame, "expected_source": list(expected),
                     "nearest_source": list(nearest), "selection_matches": nearest == expected,
                     "expected_source_mae": errors[expected],
                     "nearest_source_mae": errors[nearest]})
    return {"frames": rows, "matching_source_frames": sum(r["selection_matches"] for r in rows),
            "frame_count": len(rows)}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--ffmpeg-only", action="store_true",
                        help="Explicit partial trial; does not claim native MLT comparison")
    options = parser.parse_args(argv)
    for binary in ("ffmpeg", "ffprobe", "git", *(() if options.ffmpeg_only else ("melt",))):
        if not shutil.which(binary):
            parser.error(f"Required actual executable unavailable: {binary}")
    os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
    os.environ.setdefault("LC_ALL", "C")
    repo = Path(__file__).resolve().parents[1]
    results = []
    with tempfile.TemporaryDirectory(prefix="zx7-research-editor-") as temporary:
        root = Path(temporary)
        records, candidates = make_sources(root)
        original = make_plan(records)
        revised = copy.deepcopy(original)
        revised["tracks"][2]["clips"][0].update(position_frame=7, first_frame=2, end_frame=5)
        parent = root / "baseline.mlt"
        for label, plan in (("baseline", original), ("revision", revised)):
            source = root / f"{label}.json"
            source.write_text(json.dumps(plan))
            native = root / f"{label}.mlt"
            if label == "baseline":
                export_owned_mlt(source, root, root / "vault", native)
            else:
                patch = root / "patch.json"
                patch.write_text(json.dumps({"operations": [
                    {"op": "replace", "path": f"/tracks/2/clips/0/{key}", "value": value}
                    for key, value in (("position_frame", 7), ("first_frame", 2), ("end_frame", 5))]}))
                revise_owned_mlt_project(parent, patch, root, root / "vault", native)
            reopened = recover_original_mlt_plan(native, root, root / "vault")
            if reopened["plan"] != plan or not reopened["lossless_typed_native_roundtrip"]:
                raise ValueError("Native revision/reopen did not retain the diagnostic intent")
            for engine in (("ffmpeg",) if options.ffmpeg_only else ("ffmpeg", "mlt")):
                output = root / f"{label}-{engine}.mp4"
                started = time.monotonic()
                if engine == "mlt":
                    receipt = render_owned_mlt(native, root, output)
                else:
                    request = root / f"{label}-composition.json"
                    request.write_text(json.dumps(composition(plan)))
                    receipt = render_composition(request, root, root / "vault", output)
                elapsed = time.monotonic() - started
                results.append({"label": label, "engine": engine, "seconds": elapsed,
                                "output_sha256": hashlib.sha256(output.read_bytes()).hexdigest(),
                                "native_reopen_matched": True,
                                "assessment": assess(output, plan, candidates),
                                "native_output_frames": receipt.get("frames")})
    report = {"schema": 1,
              "source_commit": run(["git", "-C", str(repo), "rev-parse", "HEAD"]).decode().strip(),
              "working_tree_dirty": bool(run(["git", "-C", str(repo), "status", "--porcelain"])),
              "probe_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
              "ffmpeg_version": run(["ffmpeg", "-version"]).decode().splitlines()[0],
              "mlt_comparison_executed": not options.ffmpeg_only,
              "scope": "12fps opaque three-track source-frame selection, one native revision and reopen",
              "not_established": ["rational NTSC", "long projects", "sound", "alpha/effects/color fidelity",
                                  "crash recovery", "resource benchmark", "creative quality/model autonomy"],
              "results": results}
    if not options.ffmpeg_only:
        report["melt_version_output"] = subprocess.run(
            ["melt", "-version"], capture_output=True, text=True, timeout=30).stderr[:1000]
    options.out.parent.mkdir(parents=True, exist_ok=True)
    options.out.write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps({"mlt_comparison_executed": report["mlt_comparison_executed"],
                      "results": [{"label": r["label"], "engine": r["engine"],
                                   "matching_source_frames": r["assessment"]["matching_source_frames"],
                                   "frame_count": r["assessment"]["frame_count"]} for r in results]}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
