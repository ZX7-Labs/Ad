"""Original reviewed video is accessible as signed media bytes to a creative tool."""
from __future__ import annotations
import hashlib
import importlib.util
import json
import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

from studio_next.body_observation import produce_review_bundle
from studio_next.body_review_access import read_verified_review,extract_verified_review_frame
from studio_next.body_integration import body_catalog,validate_witness
from studio_next.body_materials import fingerprint_physical_inputs
from studio_next.media_vault import MediaVault,sha256_file


@unittest.skipUnless(shutil.which("ffmpeg") and shutil.which("ffprobe")
    and importlib.util.find_spec("PIL"),
    "Original picture/sound decoders are required to prove a genuine review reader")
class PhysicalReviewReadbackTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory()
        self.root=Path(self.tmp.name)
        self.film=self.root/"artist-original-picture-and-sound.mp4"
        recorded=subprocess.run(["ffmpeg","-hide_banner","-loglevel","error","-y",
            "-f","lavfi","-i","testsrc2=size=160x90:rate=12:duration=1.5",
            "-f","lavfi","-i","sine=frequency=555:duration=1.5",
            "-c:v","libx264","-pix_fmt","yuv420p","-c:a","aac",
            "-shortest",str(self.film)],capture_output=True,text=True,timeout=90)
        if recorded.returncode!=0:
            raise RuntimeError("Actual recorded film fixture did not render: "+recorded.stderr)
        self.vault=MediaVault(self.root/"vault")
        self.receipt=self.vault.ingest(self.film,mime="video/mp4",
            rights="owner_supplied",source_type="owner_upload",
            source_id="original-film-readback-sound",
            evidence="Original unit test picture and synchronized audio generated by verified FFmpeg",
            owner_or_generator="owner")
        self.plan=self.root/"actual-review.json"
        self.plan.write_text(json.dumps({
             "media":{"source":"zx7:sha256:"+self.receipt["asset_id"],
                 "asset_id":self.receipt["asset_id"],
                 "attestation_id":self.receipt["attestation_id"]},
             "timecodes_seconds":[0.2,0.9],
             "audio_windows_seconds":[[0.1,0.7]]}),encoding="utf-8")
        self.bundle=self.root/"physically-reviewed.zxreview"
        self.proof=produce_review_bundle(self.plan,self.root,
                                        self.root/"vault",self.bundle)
    def tearDown(self):self.tmp.cleanup()

    def test_model_reads_factual_original_image_and_audio_evidence_and_extracts_one_exact_png(self):
        catalog=body_catalog(self.root)
        status={x["id"]:x for x in catalog.discover()}
        self.assertEqual(status["body.review_data"]["status"],"installed")
        self.assertEqual(status["body.review_frame"]["status"],"installed")
        self.assertEqual(status["body.review_frame"]["schema"]["required"],
                         ["bundle","bundle_sha256","frame_index","out"])
        before=sha256_file(self.film)
        args={"bundle":self.bundle.name,"bundle_sha256":self.proof["sha256"]}
        data=catalog.invoke("body.review_data",args,allowed_access={"read"})
        self.assertEqual(data["original_source_sha256"],before)
        self.assertTrue(validate_witness("body.review_data",data))
        self.assertEqual(len(data["frames"]),2)
        self.assertEqual(len(data["audio_windows"]),1)
        self.assertFalse(data["human_artistic_quality_approved"])
        self.assertFalse(data["no_actor_continuity_or_narrative_understanding_claimed"] is False)
        photo=self.root/"frame-for-director.png"
        args.update({"frame_index":2,"out":photo.name})
        with self.assertRaises(PermissionError):
            catalog.invoke("body.review_frame",args,allowed_access={"read"})
        material=fingerprint_physical_inputs("body.review_frame",args,self.root)
        self.assertIn(self.proof["sha256"],[x["sha256"] for x in material])
        view=catalog.invoke("body.review_frame",args,
                            allowed_access={"read","write"})
        self.assertTrue(validate_witness("body.review_frame",view))
        self.assertEqual(view["sha256"],sha256_file(photo))
        self.assertEqual(sha256_file(self.film),before)
        with self.assertRaises(ValueError):
            catalog.invoke("body.review_frame",{**args,"frame_index":99,
                 "out":"nonexistent.png"},allowed_access={"read","write"})
        self.assertFalse((self.root/"nonexistent.png").exists())

    def test_competing_review_frame_is_never_overwritten_or_deleted(self):
        original=self.root/"first-artist-verified.png"
        extract_verified_review_frame(self.bundle,self.proof["sha256"],
                                      self.root,1,original)
        expected=sha256_file(original)
        output=self.root/"second-director-race.png"
        linker=os.link
        raced=False
        from studio_next import body_review_access
        def first_editor_wins(stage,destination,*args,**kwargs):
            nonlocal raced
            if Path(destination)==output:
                self.assertIn(".zx7-review-frame-",str(stage))
                shutil.copyfile(original,output)
                raced=True
            return linker(stage,destination,*args,**kwargs)
        with patch.object(body_review_access.os,"link",side_effect=first_editor_wins):
            with self.assertRaises(FileExistsError):
                extract_verified_review_frame(self.bundle,self.proof["sha256"],
                                              self.root,2,output)
        self.assertTrue(raced)
        self.assertEqual(sha256_file(output),expected)
        from studio_next.media_vault import verify_media_container
        verify_media_container(output,"image/png")
        self.assertFalse(list(self.root.glob(".zx7-review-frame-*")))

    def test_stale_review_digest_or_malicious_archive_does_not_expose_pixels(self):
        good={"bundle":self.bundle.name,"bundle_sha256":self.proof["sha256"]}
        for bad in ({**good,"bundle_sha256":"0"*64},
                    {**good,"bundle_sha256":"not a SHA256"}):
            with self.assertRaisesRegex(ValueError,"bytes differ"):
                read_verified_review(self.bundle,bad["bundle_sha256"],self.root)
        with self.assertRaises(ValueError):
            extract_verified_review_frame(self.bundle,self.proof["sha256"],
                self.root,True,self.root/"bad.png")
        self.assertFalse((self.root/"bad.png").exists())
        with self.assertRaises(ValueError):
            extract_verified_review_frame(self.bundle,self.proof["sha256"],
                self.root,0,self.root/"bad.png")
        self.assertFalse((self.root/"bad.png").exists())
        self.bundle.write_bytes(b"tampered because no original cinematic source")
        self.assertFalse(validate_witness("body.review_data",{
            "path":str(self.bundle),"sha256":self.proof["sha256"]}))
        with self.assertRaises(ValueError):
            read_verified_review(self.bundle,self.proof["sha256"],self.root)

if __name__=="__main__":unittest.main()
