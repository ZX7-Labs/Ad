"""Real thumbnail, key art, motion-poster and vector/raster body primitives.

Original typography, paths, colors, layout, layering, resolution, style and
imagery are generated by the creative brain or supplied by rights-cleared
owner media. This module ONLY verifies source safety and invokes installed
Inkscape/FFmpeg tools. No look/genre/font/preset is silently imposed.
"""
from __future__ import annotations

import hashlib
import math
import re
import shutil
import subprocess
import xml.etree.ElementTree as ET
from pathlib import Path
from urllib.parse import urlsplit

_NAMESPACE="{http://www.w3.org/2000/svg}"
_FORBIDDEN={"script","foreignObject","iframe","object","embed",
            "image","feImage","audio","video"}
_URI_ATTRS={"href","src","xlink:href"}
_REMOTE=re.compile(r"(?i)(?:@import|url\s*\(|expression\s*\(|javascript:|file:|https?://|data:)")
_LOCAL_SVG_REF=re.compile(r"url\(\s*#[a-zA-Z_][\w.-]*\s*\)",re.I)
_EXTENSION={".png",".webp",".jpeg",".jpg"}


def validate_original_svg_art(source,*,max_bytes=4_000_000):
    path=Path(source)
    if not path.is_file():
        raise ValueError("Original artist-authored vector artwork is missing")
    blob=path.read_bytes()
    if not blob or len(blob)>max_bytes or b"<!DOCTYPE" in blob.upper() or (
        b"<!ENTITY" in blob.upper()):
        raise ValueError("External entity or oversized vector source is prohibited")
    try:root=ET.fromstring(blob)
    except ET.ParseError as exc:raise ValueError("Vector source is not an SVG document") from exc
    if root.tag!=_NAMESPACE+"svg":
        raise ValueError("Artist must provide actual SVG vector artwork")
    for element in root.iter():
        name=element.tag.split("}")[-1]
        if name in _FORBIDDEN:
            raise ValueError("Embedded nonlocal media or executable SVG object is forbidden")
        for k,v in element.attrib.items():
            key=k.split("}")[-1]
            if key.startswith("on"):
                raise ValueError("SVG event execution is not a graphics operation")
            if key in _URI_ATTRS:
                if not isinstance(v,str) or not v.startswith("#") or (
                        not re.fullmatch(r"#[A-Za-z_][\\w.-]*",v)):
                    raise ValueError("No external asset fetch in original graphics")
                continue
            # Local gradients and masks are legitimate world-class vector art;
            # only URLs that actually leave the source file are blocked.
            stripped=_LOCAL_SVG_REF.sub("",str(v))
            if _REMOTE.search(stripped):
                raise ValueError("SVG must contain only self-contained original graphics")
        if name=="style" and element.text and _REMOTE.search(
                _LOCAL_SVG_REF.sub("",element.text)):
            raise ValueError("External style resource in original vector design")
    return {"svg_sha256":hashlib.sha256(blob).hexdigest(),
            "xml_elements":sum(1 for _ in root.iter()),"self_contained":True}


def _measured_image(filename):
    with Path(filename).open("rb") as stream:
        start=stream.read(24)
    if start[:8]!=b"\x89PNG\r\n\x1a\n":
        raise RuntimeError("Real rasterizer did not output decoded PNG bytes")
    return {"width":int.from_bytes(start[16:20],"big"),
            "height":int.from_bytes(start[20:24],"big"),
            "sha256":hashlib.sha256(Path(filename).read_bytes()).hexdigest()}


def rasterize_original_svg(source,destination,*,width,height,runner=None,
                           finder=None):
    if any(isinstance(n,bool) or not isinstance(n,int) or n<=0
           for n in (width,height)):
        raise ValueError("Original creator must specify actual positive image dimensions")
    inspect=validate_original_svg_art(source)
    find=finder or shutil.which
    tool=find("inkscape")
    if not tool:
        raise RuntimeError("Free original vector design body unavailable: install Inkscape")
    out=Path(destination)
    if out.suffix.lower()!=".png" or out.exists():
        raise ValueError("Only new PNG outputs are supported; never overwrite source assets")
    out.parent.mkdir(parents=True,exist_ok=True)
    invoke=runner or subprocess.run
    invoke([tool,str(Path(source).resolve()),"--export-type=png",
            f"--export-filename={out.resolve()}",
            f"--export-width={width}",f"--export-height={height}"],
           check=True,timeout=300)
    if not out.is_file():
        raise RuntimeError("Installed Inkscape did not produce real thumbnail bytes")
    meta=_measured_image(out)
    if meta["width"]!=width or meta["height"]!=height:
        raise RuntimeError("Real thumbnail raster resolution changed without director consent")
    return {"created_real_original_key_art":True,
            "original_svg_sha256":inspect["svg_sha256"],
            "png_sha256":meta["sha256"],"path":str(out),
            "width":meta["width"],"height":meta["height"],
            "creative_quality_approved":False}


def extract_director_selected_frame(movie,destination,*,at_seconds,runner=None):
    from .delivery_audit import _probe_details
    observed=_probe_details(movie)
    if isinstance(at_seconds,bool) or not isinstance(at_seconds,(int,float)) or (
        not math.isfinite(at_seconds) or at_seconds<0 or
        at_seconds>=observed["duration_seconds"]):
        raise ValueError("Creator-specified frame time is outside actual encoded media")
    out=Path(destination)
    if out.suffix.lower()!=".png" or out.exists():
        raise ValueError("Do not overwrite original thumbnail or film frame")
    out.parent.mkdir(parents=True,exist_ok=True)
    (runner or subprocess.run)(["ffmpeg","-hide_banner","-loglevel","error",
        "-n","-ss",str(at_seconds),"-i",str(Path(movie)),
        "-frames:v","1",str(out)],check=True,timeout=120)
    media=_measured_image(out)
    return {"selected_time_seconds":at_seconds,"source_film_sha256":
             observed["video_sha256"],"decoded_thumbnail_sha256":media["sha256"],
            "width":media["width"],"height":media["height"],
            "film_identity_preserved":True}
