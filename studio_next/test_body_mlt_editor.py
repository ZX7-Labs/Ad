def _movie(path,color):
    subprocess.run(["ffmpeg","-hide_banner","-loglevel","error","-nostdin",
        "-f","lavfi","-i",f"color=c={color}:s=64x48:r=12:d=1",
        "-c:v","libx264","-pix_fmt","yuv420p","-frames:v","12",
        "-color_primaries","bt709","-color_trc","bt709","-colorspace","bt709",
        "-movflags","+faststart","-y",str(path)],check=True,timeout=30)


@unittest.skipUnless(shutil.which("ffmpeg") and shutil.which("ffprobe"),
                     "Real media decoder required")
class VerifiedMLTEditorialTests(unittest.TestCase):
    def _case(self,root):
        vault=MediaVault(root/"vault")
        assets=[]
        for color in ("red","blue"):
            path=root/(color+".mp4");_movie(path,color)
            record=vault.ingest(path,mime="video/mp4",rights="owner_supplied",
                source_type="owner_upload",source_id="creator-"+color,
                evidence="test fixture generated by FFmpeg",owner_or_generator="fixture")
            assets.append(record)
        def clip(which,first,end,position):
            obj=assets[which]
            return {"source":"zx7:sha256:"+obj["asset_id"],
                "asset_id":obj["asset_id"],"attestation_id":obj["attestation_id"],
                "first_frame":first,"end_frame":end,"position_frame":position,
                "audio":"intentional_silence"}
        plan={"frame_rate":{"numerator":12,"denominator":1},
              "frame_size":{"width":64,"height":48},
              "tracks":[{"clips":[clip(0,0,12,0)]},
                        {"clips":[clip(1,2,8,4)]}]}
        plan_path=root/"original.json";plan_path.write_text(json.dumps(plan))
        return plan,plan_path

    def test_exact_multitrack_placement_and_exclusive_project_publication(self):
        with tempfile.TemporaryDirectory() as temp:
            root=Path(temp);plan,source=self._case(root)
            self.assertTrue(validate_document("body.mlt_owned_export",plan))
            checked=validate_mlt_edit(plan,root,root/"vault")
            self.assertEqual(checked["frames"],12)
            self.assertEqual(len(checked["sources"]),2)
            data=build_mlt_xml(plan,checked)
            parsed=ET.fromstring(data)
            self.assertEqual(len(parsed.findall("./playlist")),2)
            self.assertEqual(len(parsed.findall("./tractor/transition")),1)
            playlists=parsed.findall("./playlist")
            self.assertEqual(playlists[1].find("./blank").attrib["length"],"4")
            self.assertEqual(playlists[1].find("./entry").attrib["in"],"2")
            self.assertEqual(playlists[1].find("./entry").attrib["out"],"7")
            target=root/"creative-edit.mlt"
            result=export_owned_mlt(source,root,root/"vault",target)
            self.assertEqual(result["sha256"],hashlib.sha256(target.read_bytes()).hexdigest())
            self.assertTrue(result["sound_intentionally_silent"])
            report=verify_owned_mlt_project(target)
            self.assertEqual(report["verified_original_sources"],2)
            self.assertEqual(report["verified_mlt_tracks"],2)
            with self.assertRaises(FileExistsError):
                export_owned_mlt(source,root,root/"vault",target)
            self.assertFalse(list(root.glob(".zx7-mlt-*")))

    def test_unattested_or_unauthorized_sound_is_never_smuggled_into_project(self):
        with tempfile.TemporaryDirectory() as temp:
            root=Path(temp);plan,_=self._case(root)
            for field,value in (("audio","preserve_source"),("source","https://example.com/movie.mp4"),
                                ("asset_id","0"*64)):
                changed=json.loads(json.dumps(plan))
                changed["tracks"][1]["clips"][0][field]=value
                with self.subTest(field=field),self.assertRaises(ValueError):
                    validate_mlt_edit(changed,root,root/"vault")

    def test_same_layer_overlap_and_unmeasured_source_range_fail_closed(self):
        with tempfile.TemporaryDirectory() as temp:
            root=Path(temp);plan,_=self._case(root)
            clip=plan["tracks"][0]["clips"][0]
            changed=json.loads(json.dumps(plan))
            duplicate={**clip,"position_frame":4,"first_frame":0,"end_frame":4}
            changed["tracks"][0]["clips"].append(duplicate)
            with self.assertRaisesRegex(ValueError,"Overlapping"):
                validate_mlt_edit(changed,root,root/"vault")
            changed=json.loads(json.dumps(plan))
            changed["tracks"][0]["clips"][0]["end_frame"]=13
            with self.assertRaisesRegex(ValueError,"exceeds"):
                validate_mlt_edit(changed,root,root/"vault")

    @unittest.skipUnless(shutil.which("melt"),"Installed MLT executable required")
    def test_model_facing_body_registry_only_exposes_real_available_mlt_adapter(self):
        from studio_next.body_capabilities import explain_operational_tool
        from studio_next.body_integration import body_catalog
        with tempfile.TemporaryDirectory() as temp:
            root=Path(temp)
            installed={tool["id"]:tool for tool in body_catalog(root).discover()}
            self.assertEqual(installed["body.mlt_owned_export"]["status"],"installed")
            doc=explain_operational_tool(root,"body.mlt_owned_export")
            self.assertEqual(doc["status"],"ready_for_execution_trial")
            self.assertIn("plan",doc["document_contracts"])
            self.assertIn("tracks",doc["document_contracts"]["plan"]["json_schema"]["properties"])

    @unittest.skipUnless(shutil.which("melt"),"Installed MLT executable required")
    def test_real_body_catalog_publishes_verified_editorial_project(self):
        from studio_next.body_integration import body_catalog
        with tempfile.TemporaryDirectory() as temp:
            root=Path(temp);self._case(root)
            result=body_catalog(root).invoke("body.mlt_owned_export",{
                "plan":"original.json","out":"actual-edit.mlt"},allowed_access={"write"})
            self.assertEqual(Path(result["path"]).name,"actual-edit.mlt")
            self.assertEqual(result["sha256"],
                             hashlib.sha256((root/"actual-edit.mlt").read_bytes()).hexdigest())
            self.assertEqual(verify_owned_mlt_project(root/"actual-edit.mlt")[
                "verified_mlt_tracks"],2)
            self.assertFalse(list(root.glob(".zx7-uncommitted-*")))

    def test_tampered_mlt_source_is_rejected_after_publication(self):
        with tempfile.TemporaryDirectory() as temp:
            root=Path(temp);plan,source=self._case(root)
            target=root/"original.mlt"
            export_owned_mlt(source,root,root/"vault",target)
            self.assertTrue(verify_owned_mlt_project(target)["verified_original_sources"])
            text=target.read_text()
            tampered=text.replace("zx7.attestation_id","plugin.load_from_url")
            target.write_text(tampered)
            with self.assertRaises(ValueError):
                verify_owned_mlt_project(target)

    @unittest.skipUnless(shutil.which("melt"),"Actual LGPL/GPL MLT runtime required")
    def test_actual_mlt_multitrack_renders_measured_decodable_video(self):
        with tempfile.TemporaryDirectory() as temp:
            root=Path(temp);plan,source=self._case(root)
            mlt=root/"edit.mlt";output=root/"render.mp4"
            export_owned_mlt(source,root,root/"vault",mlt)
            result=subprocess.run(["melt",str(mlt),"-consumer",f"avformat:{output}",
                    "vcodec=libx264","an=1","real_time=-1","threads=1",
                    "pix_fmt=yuv420p","crf=18"],capture_output=True,text=True,timeout=90)
            self.assertEqual(result.returncode,0,result.stderr[-3000:])
            self.assertTrue(output.is_file(),result.stderr[-2000:])
            decoded=json.loads(subprocess.check_output(["ffprobe","-v","error",
                "-count_frames","-select_streams","v:0",
                "-show_entries","stream=nb_read_frames,width,height",
                "-of","json",str(output)],timeout=30))
            stream=decoded["streams"][0]
            self.assertEqual((stream["width"],stream["height"]),(64,48))
            self.assertEqual(int(stream["nb_read_frames"]),12)
            raw=subprocess.check_output(["ffmpeg","-v","error","-xerror",
                "-i",str(output),"-pix_fmt","rgb24","-f","rawvideo","-vsync","0","-"],
                timeout=30)
            pitch=64*48*3
            self.assertEqual(len(raw),12*pitch)
            def center(frame):
                offset=frame*pitch+(24*64+32)*3
                return tuple(raw[offset:offset+3])
            start=center(0);overlay=center(5);finish=center(11)
            self.assertGreater(start[0],start[2]+70,("red base",start))
            self.assertGreater(overlay[2],overlay[0]+70,
                               ("actual blue upper timeline layer",overlay))
            self.assertGreater(finish[0],finish[2]+70,("red after overlay",finish))
            subprocess.run(["ffmpeg","-hide_banner","-loglevel","error",
                "-xerror","-i",str(output),"-f","null","-"],check=True,timeout=30,
                capture_output=True)


if __name__=="__main__":unittest.main()
